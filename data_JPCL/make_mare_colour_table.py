#!/usr/bin/env python3
"""Colour-coded table of the strong-coupling ingredient MAREs (R2-ii, revision 1).

Purpose: log-scale bar charts (Figs. 1, 4, 10a) exaggerate differences between very good models and
compress differences between poor ones. This script writes the same MAREs as a LaTeX
table with linear colour bands, for the SI (Table S6):
    Hookium (20 omega, FCI rows), He series (FCI rows, all ions present), atoms/ions (H-Zn).
Same definitions as the figure scripts: 100*|W_model - W_SCE|/|W_SCE| on the PyOEP density,
averaged over systems; systems with W_SCE = 0 (H atom, W'_inf) are skipped.
Output: ../SI_mare_colour_table.tex (\\input by SI.tex). Prints the numbers.
"""
from pathlib import Path
import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
MODELS = ["LDA", "PBE", "TPSS", "R2SCAN", "PC", "mPC", "hPC", "fPC", "ePC"]
NAMES = {"R2SCAN": r"r$^2$SCAN"}
HE_SYS = ["H-", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne", "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar"]
BANDS = [(1, "mareA"), (3, "mareB"), (10, "mareC"), (30, "mareD"), (np.inf, "mareE")]


def mare(df, model, which):
    ref = pd.to_numeric(df["PYOEP_Winf" if which == "W" else "PYOEP_T_ZP_prl"], errors="coerce")
    val = pd.to_numeric(df[f"PYOEP_{'W_inf' if which == 'W' else 'Wp_inf'}_{model}"], errors="coerce")
    ok = ref.notna() & val.notna() & (ref.abs() > 0)
    return float(100 * np.mean(np.abs(val[ok] - ref[ok]) / np.abs(ref[ok])))


def load():
    h = pd.read_csv(HERE / "hookium" / "merged_hooke_results.csv"); h.columns = h.columns.str.strip()
    h = h[h.density_type.astype(str).str.upper() == "FCI"].drop_duplicates("omega")
    e = pd.read_csv(HERE / "he_series" / "merged_results.csv"); e.columns = e.columns.str.strip()
    e = e[(e.density_type == "FCI") & e.system.isin(HE_SYS) & e.source_folder.ne("he_se")].drop_duplicates("system")
    a = pd.read_csv(HERE / "atoms_ions" / "merged_results.csv"); a.columns = a.columns.str.strip()
    a = a[a.density_type.astype(str).str.upper().isin({"FCI", "CCSDT", "CCSD"})].drop_duplicates("system")
    return {"Hookium": h, "He": e, "Atoms": a}


def cell(x):
    col = next(c for lim, c in BANDS if x < lim)
    txt = f"{x:.2f}" if x < 1 else (f"{x:.1f}" if x < 10 else f"{x:.0f}")
    return rf"\cellcolor{{{col}}}{txt}"


def main():
    sets = load()
    nhe = len(sets["He"])
    rows, printed = [], []
    for m in MODELS:
        vals = [mare(sets[s], m, w) for s in ("Hookium", "He", "Atoms") for w in ("W", "Wp")]
        printed.append((m, vals))
        rows.append(f"{NAMES.get(m, m):9s} & " + " & ".join(cell(v) for v in vals) + r" \\")
    tex = [
        r"% Generated by data_JPCL/make_mare_colour_table.py -- do not edit by hand.",
        r"\definecolor{mareA}{RGB}{26,152,80}\definecolor{mareB}{RGB}{145,207,96}",
        r"\definecolor{mareC}{RGB}{254,224,139}\definecolor{mareD}{RGB}{252,141,89}\definecolor{mareE}{RGB}{215,48,39}",
        r"\begin{tabular}{l cc cc cc}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Hookium} & \multicolumn{2}{c}{He series} & \multicolumn{2}{c}{Atoms and ions} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
        r"Model & $W_\infty$ & $W'_\infty$ & $W_\infty$ & $W'_\infty$ & $W_\infty$ & $W'_\infty$ \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    (HERE.parent / "SI_mare_colour_table.tex").write_text("\n".join(tex) + "\n")
    print(f"He series rows used: {nhe}; Hookium omegas: {len(sets['Hookium'])}; atoms: {len(sets['Atoms'])}")
    print(f"{'model':8s} " + " ".join(f"{c:>9s}" for c in ("Hook W", "Hook Wp", "He W", "He Wp", "At W", "At Wp")))
    for m, v in printed:
        print(f"{m:8s} " + " ".join(f"{x:9.2f}" for x in v))
    print("written:", HERE.parent / "SI_mare_colour_table.tex")


if __name__ == "__main__":
    main()

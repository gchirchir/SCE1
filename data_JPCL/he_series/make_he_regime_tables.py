#!/usr/bin/env python3
"""He isoelectronic series: error statistics by nuclear charge (R2-7, revision 1).

Purpose: test whether the He-series MAREs are dominated by the ions with large Z. This script writes two SI
tables (\\input by SI.tex) with the MAREs over all 18 ions (H- ... Ar16+), over Z <= 10 and Z >= 11
separately, without H- (Z >= 2), and the share of the ions Z >= 11 in the 18-ion mean (uniform: 8/18 = 44 %):
  Table S13  W_inf and W'_inf of the nine models vs exact SCE (PyOEP density)
  Table S14  SPL and genISI2 correlation energies vs FCI (exact SCE or model ingredients)
Same data and formulas as Figs. 4-6 (FCI rows of merged_results.csv, PyOEP density).
Output: ../../SI_he_regime_tables.tex (macros \\heTabIng, \\heTabEc). Prints the numbers quoted in the text.
"""
from pathlib import Path
import numpy as np
import pandas as pd

from plot import spl_corr, genisi2_corr

HERE = Path(__file__).resolve().parent
Z_MAP = {"H-": 1, "He": 2, "Li": 3, "Be": 4, "B": 5, "C": 6, "N": 7, "O": 8, "F": 9, "Ne": 10,
         "Na": 11, "Mg": 12, "Al": 13, "Si": 14, "P": 15, "S": 16, "Cl": 17, "Ar": 18}
MODELS = ["LDA", "PBE", "TPSS", "R2SCAN", "PC", "mPC", "hPC", "fPC", "ePC"]
NAMES = {"R2SCAN": r"r$^2$SCAN"}


def fmt(x):
    return f"{x:.2f}" if x < 10 else (f"{x:.1f}" if x < 100 else f"{x:.0f}")


def stats(z, relerr):
    e = 100 * np.abs(relerr)
    return [e.mean(), e[z <= 10].mean(), e[z >= 11].mean(), e[z >= 2].mean(), 100 * e[z >= 11].sum() / e.sum()]


def table(rows, a, b):
    sub = r" & all & $Z\le10$ & $Z\ge11$ & no H$^-$ & share"
    out = [r"\begin{tabular}{l ccccc ccccc}", r"\toprule",
           rf" & \multicolumn{{5}}{{c}}{{{a}}} & \multicolumn{{5}}{{c}}{{{b}}} \\",
           r"\cmidrule(lr){2-6}\cmidrule(lr){7-11}", "Model" + sub + sub + r" \\", r"\midrule"]
    for name, v, rule in rows:
        out.append(f"{name:9s} & " + " & ".join(fmt(x) for x in v) + r" \\" + (r" \midrule" if rule else ""))
    return out + [r"\bottomrule", r"\end{tabular}"]


def main():
    d = pd.read_csv(HERE / "merged_results.csv")
    d.columns = d.columns.str.strip()
    d = d[(d.density_type == "FCI") & d.system.isin(Z_MAP) & d.source_folder.ne("he_se")].drop_duplicates("system").copy()
    d = d.assign(Z=d.system.map(Z_MAP)).sort_values("Z")
    z = d.Z.to_numpy()
    n = lambda c: pd.to_numeric(d["PYOEP_" + c], errors="coerce").to_numpy(float)
    w0, gl2, ec, wi, wp = n("W0"), 0.5 * n("W0_prime"), n("E_c"), n("Winf"), n("T_ZP_prl")
    spl = lambda a: np.array([spl_corr(x, y, q) for x, y, q in zip(w0, gl2, a)])
    gen = lambda a, b: np.array([genisi2_corr(x, y, q, r) for x, y, q, r in zip(w0, gl2, a, b)])
    print(f"{len(z)} ions, Z = {z.min()}-{z.max()}; uniform share of Z >= 11: {100 * np.mean(z >= 11):.0f} %")

    ing, ene = [], []
    for m in MODELS:
        a, b = n("W_inf_" + m), n("Wp_inf_" + m)
        v = stats(z, (a - wi) / np.abs(wi)) + stats(z, (b - wp) / np.abs(wp))
        ing.append((NAMES.get(m, m), v, False))
        print(f"  {m:7s} W " + " ".join(f"{x:7.2f}" for x in v[:5]) + " | W' " + " ".join(f"{x:7.2f}" for x in v[5:]))
    for m in ["SCE"] + MODELS:
        a, b = (wi, wp) if m == "SCE" else (n("W_inf_" + m), n("Wp_inf_" + m))
        es, eg = (spl(a) - ec) / np.abs(ec), (gen(a, b) - ec) / np.abs(ec)
        v = stats(z, es) + stats(z, eg)
        ene.append(("exact SCE" if m == "SCE" else NAMES.get(m, m), v, m == "SCE"))
        print(f"  {m:7s} SPL " + " ".join(f"{x:7.2f}" for x in v[:5]) + " | gen " + " ".join(f"{x:7.2f}" for x in v[5:])
              + f" | H- share SPL {100 * abs(es[0]) / np.abs(es).sum():.0f} %, gen {100 * abs(eg[0]) / np.abs(eg).sum():.0f} %")
    out = HERE.parent.parent / "SI_he_regime_tables.tex"
    out.write_text("% Generated by data_JPCL/he_series/make_he_regime_tables.py -- do not edit by hand.\n"
                   + "\\def\\heTabIng{%\n" + "\n".join(table(ing, r"$W_\infty$", r"$W'_\infty$")) + "}\n"
                   + "\\def\\heTabEc{%\n" + "\n".join(table(ene, "SPL", "genISI2")) + "}\n")
    print("written:", out)


if __name__ == "__main__":
    main()
